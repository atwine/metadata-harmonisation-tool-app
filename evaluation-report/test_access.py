"""Access tests: proof that the rules in ACCESS.md hold.

Generated by the access-guard-audit skill and adapted for an app with no
user accounts: the "roles" are where a request comes from (see ACCESS.md
section 2).

  * test_access_rule: every route x every browser-side role.
  * test_every_route_has_rules: fails when a route exists with no case for
    some role, so a new route can't ship without a decision.
  * test_*_listens_on_localhost: the "network" role. Other devices are kept
    out by where the API listens, so these read the real run settings.

Each test runs in a throwaway folder, so input/, results/ and db/ are never
the real ones.
"""

import json
import os
import runpy
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest
from fastapi.routing import APIRoute
from fastapi.testclient import TestClient

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "backend"))

import main  # noqa: E402

app = main.app

ROLES = ["local", "website", "rebinding"]
PUBLIC_ROUTES: set[tuple[str, str]] = set()

STUDY = "ACE_Test"
LOCAL_HOST = "localhost:8000"
LOCAL_ORIGIN = "http://localhost:8080"
EVIL_ORIGIN = "https://evil.example"
EVIL_HOST = "evil.example:8000"


@pytest.fixture
def client(tmp_path, monkeypatch):
    study = tmp_path / "input" / STUDY
    study.mkdir(parents=True)
    (study / "dataset_variables.csv").write_text("variable_name,description\nage,Age in years\n")
    (study / "example_data.csv").write_text("age\n34\n51\n")
    monkeypatch.chdir(tmp_path)

    async def no_refresh():
        return None

    monkeypatch.setattr(main, "refresh_ontology", no_refresh)
    with TestClient(app, base_url=f"http://{LOCAL_HOST}") as c:
        yield c


ALLOW = "allow"
DENY = "deny"
SIMPLE_METHODS = {"GET", "HEAD", "POST"}


@dataclass(frozen=True)
class Case:
    method: str
    route: str
    role: str
    url: str
    expect: str
    why: str

    @property
    def id(self) -> str:
        return f"{self.role} {self.method} {self.url} -> {self.expect} ({self.why})"


def _url(path: str) -> str:
    return path.replace("{study_name}", STUDY).replace("{variable_name}", "age")


def _api_routes():
    for route in app.routes:
        if isinstance(route, APIRoute):
            for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
                yield method, route.path


# ACCESS.md grid: local may use every route; website and rebinding may use none.
CASES: list[Case] = []
for _method, _path in _api_routes():
    CASES += [
        Case(_method, _path, "local", _url(_path), ALLOW, "the researcher uses every route"),
        Case(_method, _path, "website", _url(_path), DENY, "other websites get nothing"),
        Case(_method, _path, "rebinding", _url(_path), DENY, "DNS-rebinding sites get nothing"),
    ]


def _form_for(path: str, method: str):
    """The required form fields and files of a route, filled the way an
    attacker's HTML form would fill them."""
    from fastapi.params import File

    route = next(
        r for r in app.routes
        if isinstance(r, APIRoute) and r.path == path and method in r.methods
    )
    fields, files = {}, {}
    for param in route.dependant.body_params:
        if not param.required:
            continue
        if isinstance(param.field_info, File):
            files[param.alias] = ("x.csv", b"variable_name,description\nplanted,planted\n", "text/csv")
        else:
            fields[param.alias] = "planted"
    return fields, files or None


def _blocked(response) -> bool:
    """True when an access check refused the request before the route ran:
    a 403 from the app, or a 400 from the CORS preflight check."""
    return response.status_code == 403 or (
        response.status_code == 400 and "CORS" in response.text
    )


def _send(client, case: Case):
    if case.role == "local":
        headers = {"Origin": LOCAL_ORIGIN}
        return client.request(case.method, case.url, headers=headers), "sent"

    if case.role == "rebinding":
        # The attacker's page and the API look same-origin to the browser,
        # so it can send anything and read the reply.
        headers = {"Host": EVIL_HOST}
        if case.method != "GET":
            headers["Origin"] = f"http://{EVIL_HOST}"
        return client.request(case.method, case.url, headers=headers), "sent"

    # website: what a browser lets another site do.
    if case.method == "GET":
        r = client.get(case.url, headers={"Origin": EVIL_ORIGIN})
        return r, "read"
    if case.method in SIMPLE_METHODS:
        # A hidden HTML form or no-cors fetch: sent without asking, but only
        # as text/plain or a form (with files). JSON needs a preflight. The
        # route is reached if either format gets past FastAPI's parsing.
        headers = {"Origin": EVIL_ORIGIN}
        as_text = client.request(
            case.method, case.url, headers={**headers, "Content-Type": "text/plain"},
            content=b'{"study": "x"}',
        )
        if as_text.status_code != 422:
            return as_text, "sent"
        fields, files = _form_for(case.route, case.method)
        as_form = client.request(case.method, case.url, headers=headers, data=fields, files=files)
        return as_form, "sent"
    # PUT and DELETE: the browser asks first (preflight) and sends nothing
    # unless the API says yes.
    r = client.options(
        case.url,
        headers={"Origin": EVIL_ORIGIN, "Access-Control-Request-Method": case.method},
    )
    return r, "preflight"


@pytest.mark.parametrize("case", CASES, ids=lambda c: c.id)
def test_access_rule(client, case: Case):
    response, how = _send(client, case)

    if case.expect == ALLOW:
        assert not _blocked(response), (
            f"{case.role} was refused ({response.status_code}) on {case.method} "
            f"{case.url} but ACCESS.md says: {case.why}"
        )
        return

    if how == "read":
        # The browser sends the GET but only hands the reply to the page if
        # the API allows that origin. Denied means the page can't read it.
        allowed = response.headers.get("access-control-allow-origin")
        assert allowed not in (EVIL_ORIGIN, "*"), (
            f"ACCESS LEAK: {EVIL_ORIGIN} can read {case.method} {case.url}. "
            f"ACCESS.md says: {case.why}"
        )
    elif how == "preflight":
        assert _blocked(response), (
            f"ACCESS LEAK: the API agreed to let {EVIL_ORIGIN} send "
            f"{case.method} {case.url}. ACCESS.md says: {case.why}"
        )
    elif case.role == "website":
        # 422 means FastAPI couldn't parse any body a website is able to
        # send, so the route never ran.
        assert _blocked(response) or response.status_code == 422, (
            f"ACCESS LEAK: a background request from {EVIL_ORIGIN} reached "
            f"{case.method} {case.url} (status {response.status_code}). "
            f"ACCESS.md says: {case.why}"
        )
    else:
        assert _blocked(response), (
            f"ACCESS LEAK: {case.role} request reached {case.method} {case.url} "
            f"(status {response.status_code}). ACCESS.md says: {case.why}"
        )


def test_every_route_has_rules():
    covered = {(c.method, c.route, c.role) for c in CASES}
    access_md = (REPO / "ACCESS.md").read_text(encoding="utf-8")
    missing = []
    for method, path in _api_routes():
        if (method, path) in PUBLIC_ROUTES:
            continue
        if f"| {method} | {path} |" not in access_md:
            missing.append(f"{method} {path} has no row in ACCESS.md section 4")
        missing += [
            f"{method} {path} as {role}"
            for role in ROLES
            if (method, path, role) not in covered
        ]
    assert not missing, (
        "These routes have no access rule. Decide who may use them in "
        "ACCESS.md, then add CASES:\n  " + "\n  ".join(missing)
    )


# ---- what a real attack gets, end to end ------------------------------------


def test_local_researcher_can_list_and_clear(client):
    headers = {"Origin": LOCAL_ORIGIN}
    assert [s["name"] for s in client.get("/api/studies/", headers=headers).json()] == [STUDY]
    assert client.post("/api/initialise/clear-workspace", headers=headers).status_code == 200
    assert client.get("/api/studies/", headers=headers).json() == []


def test_website_cannot_wipe_the_workspace(client):
    client.post(
        "/api/initialise/clear-workspace",
        headers={"Origin": EVIL_ORIGIN, "Content-Type": "text/plain"},
    )
    assert (Path("input") / STUDY / "example_data.csv").exists(), (
        "ACCESS LEAK: a background request from another website deleted every study"
    )


def test_rebinding_site_cannot_read_studies(client):
    r = client.get("/api/studies/", headers={"Host": EVIL_HOST})
    assert _blocked(r), (
        f"ACCESS LEAK: a DNS-rebinding site read the study list: {r.text[:200]}"
    )


# ---- network role: where the API listens ------------------------------------


def test_run_backend_listens_on_localhost_by_default(monkeypatch):
    import uvicorn

    seen = {}
    monkeypatch.delenv("MHT_BIND_ADDRESS", raising=False)
    monkeypatch.setattr(uvicorn, "run", lambda *a, **kw: seen.update(kw))
    runpy.run_path(str(REPO / "run_backend.py"), run_name="__main__")
    assert seen.get("host") == "127.0.0.1", (
        f"ACCESS LEAK: python run_backend.py listens on {seen.get('host')}, "
        "so other devices on the network can reach the API"
    )


@pytest.mark.skipif(shutil.which("docker") is None, reason="docker not installed")
@pytest.mark.parametrize("compose_file", ["docker-compose.yml", "docker-compose.hub.yml"])
def test_compose_publishes_on_localhost_by_default(compose_file):
    env = {k: v for k, v in os.environ.items() if k != "MHT_BIND_ADDRESS"}
    out = subprocess.run(
        ["docker", "compose", "-f", compose_file, "config", "--format", "json"],
        cwd=REPO, env=env, capture_output=True, text=True, check=True,
    ).stdout
    exposed = [
        f"{name} port {p.get('published')} on {p.get('host_ip') or '0.0.0.0 (every network)'}"
        for name, svc in json.loads(out)["services"].items()
        for p in svc.get("ports", [])
        if p.get("host_ip") != "127.0.0.1"
    ]
    assert not exposed, (
        f"ACCESS LEAK: {compose_file} publishes ports beyond this computer: "
        + "; ".join(exposed)
    )
